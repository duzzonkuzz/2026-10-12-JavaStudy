/*
 *   1. 다형성 
 *       => 같은 메소드를 이용해서 새로운 기능 생성 / 기존의 메소드를 재정의 
 *          | 오버로딩                          | 오버라이딩 
 *       --------------------------------------
 *                오버로딩            오버라이딩 
 *       --------------------------------------
 *        위치     같은 클래스안       상속받은 클래스 
 *       --------------------------------------
 *        형식     메소드 동일         메소드 동일 
 *                매개변수의 갯수      매개변수가 동일 
 *                / 데이터형이 다르다
 *                리턴형은 관계없다     리턴형이 동일 
 *                접근지정어 관계없다   접근지정어 확장 / 축소 불가능 
 *                
 *       private < default < protected < public 
 *       --------------------------------------
 *        사용처    새로운 기능 추가     재정의 
 *                                 => DB 변경  
 *                                 => 추상클래스 / 인터페이스                      
 *       --------------------------------------
 *       
 *       자바 재사용 기법 
 *       ------------
 *       = 변경없이 재사용 : has-a = 포함 클래스 (웹)
 *       = 변경후에 재사용 : is-a = 상속 
 *                       ----------- 추상 클래스 / 인터페이스 
 *      1) 상속 
 *         기존의 클래스의 모든 기능(메소드) 변수 => 받아서 새로운 클래스로 확장해서 
 *                                          만든다 
 *         => 확장 : extends 
 *         
 *          => 목적 
 *             코드 재사용 (소스 간결하다)
 *             class A
 *             {
 *                int a,b,c;
 *                void display(){}
 *             }
 *             class B extends A
 *             {
 *                //int a,b,c;
 *                //void display(){} => 재정의
 *             }
 *             유지보수가 용이 
 *             신뢰성이 뛰어나다 => 이미 상용화되는 상태 
 *          => 장점 
 *             유지보수 / 신뢰성 / 간결성 
 *          => 단점 
 *             속도가 늦다 (최적화 문제)
 *             메모리가 비대 
 *               = 상속 내린 클래스 => 메모리할당 
 *               = 상속 받은 클래스 => 메모리할당
 *                 --------- super -------
 *                 
 *                 -----------------------
 *                 
 *                 --------- this -------
 *                 
 *                 ----------------------
 *             가독성이 떨어진다 
 *             ---- 메소드 내용 / 변수의 사용처를 모른다 
 *             제약조건이 많이 존재 / 결합성 높아진다 
 *                               ----- 클래스 수정 => 다른 클래스 영향 
 *          => 상속 예외 조건 
 *             생성자 / static => 사용이 가능하게 
 *             private => 상속은 된다 (접근이 불가능)
 *               => protected 사용 권장 
 *               => getter / setter 
 *             초기화 블록 : 인스턴스 블록 {} / 정적 블록 static{}
 *             
 *             변수의 초기화 
 *             ----------
 *             1. 명시적인 초기화 private int age=10;
 *             ---------------------------------
 *             2. static {} => 변수가 static 
 *             3. 인스턴스 블록 {}
 *             4. 생성자 => 변수가 인스턴스
 *             --------------------------------- 면시적 초기화가 안되는 경우
 *                => 클래스 블록안에서는 구현 (파일 읽기 / 웹 연결 / 윈도우 UI 
 *                                       제어문 / 연산자 사용) 
 *             *** 가장 먼저는 명시적 초기화 가능 ...
 *             *** static / 블록 , 메소드 => 인스턴스 사용이 불가능 
 *          => this / super 
 *                    | 상속받은 클래스 객체 
 *             | 자신의 클래스 객체
 *             ---------------------------- 인스턴스와 관련
 *                                          static {} / static메소드에서는 사용이 안됨
 *          => 자바의 클래스는 단일 상속만 가능 
 *          class A
 *          {
 *          }
 *          class B
 *          {
 *          }
 *          class C extends A,B => 오류 
 *          
 *          class A
 *          {
 *          }
 *          class B extends A
 *          {
 *          }
 *          class C extends B
 *          {
 *          }
 *          ===== 보완 => interface 
 *          
 *       메모리 할당 
 *       ---------
 *       class A
 *       {
 *          int a,b;
 *          public void aaa(){}
 *       }
 *       class B extends A
 *       {
 *           int c;
 *           public void bbb(){}
 *       }
 *       
 *       B b=new B();  ==> new A() / new B()
 *        stack      heap
 *       ---b----
 *        0x100
 *       --------   --------- 0x100------
 *                   --- super----
 *                      --a---
 *                      
 *                      ------
 *                      
 *                      --b--
 *                      
 *                      -----
 *                      
 *                      --aaa()--
 *                      
 *                      -----------
 *                   -------------
 *                   
 *                   ------ this -----
 *                   
 *                      ---c---
 *                      
 *                      -------
 *                      
 *                      ---bbb()--
 *                      
 *                      ----------
 *                   ----------------
 *                  ---------------------
 */
class A
{
	public A()
	{
		System.out.println("A() Call...");
	}
}
class B extends A
{
	public B()
	{
		System.out.println("B() Call...");
	}
}
